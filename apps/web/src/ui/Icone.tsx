type Props = {
  nome: string;
  size: number;
  color?: string;
  className?: string;
  style?: CSSProperties;
};

export function Icone({ nome, size, color = 'currentColor', className, style }: Props) {
  const Desenho = MAPA[nome];
  if (!Desenho) {
    if (import.meta.env.DEV) console.warn(`[Icone] nome sem desenho na web: "${nome}"`);
    return (
      <span
        aria-hidden="true"
        className={className}
        style={{
          display: 'inline-block',
          width: size,
          height: size,
          borderRadius: '50%',
          border: `2px solid ${color}`,
          flexShrink: 0,
          ...style,
        }}
      />
    );
  }
  return (
    <Desenho
      aria-hidden="true"
      size={size}
      color={color}
      strokeWidth={2}
      className={className}
      style={{ flexShrink: 0, ...style }}
    />
  );
}
